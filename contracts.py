"""Shared data contracts (task S-2).

Owned jointly by workstreams B (simulation core) and C (agents & protocol).
Once both sides import this file, change it only after both teammates agree.

Conventions
- All times are float minutes since local midnight at the DESTINATION airport on the
  scenario date (values can exceed 1440). DOT departure times are origin-local, so the
  scenario builder converts them using SCHEDULED_TIME.
- Fuel in kg, money in USD.
- A Scenario is split into a PUBLIC part every agent sees and one PRIVATE part per
  organisation. `Scenario.view(role)` drops the other organisations' private data;
  agents must only ever receive views.

Message / ResultRow schemas belong to workstreams C / D and are not defined here.
"""
from __future__ import annotations

from enum import Enum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

Role = Literal["atc", "pilot", "ground"]
ROLES: tuple[Role, ...] = ("atc", "pilot", "ground")


class _Model(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class Provenance(str, Enum):
    REAL = "real"                  # straight from the DOT 2015 file
    REAL_DERIVED = "real_derived"  # computed from real data (e.g. tail chains)
    EXTERNAL = "external"          # other public source (e.g. FAA aircraft registry)
    ORGANISER = "organiser"        # organiser workbook (synthetic values, officially provided)
    SYNTHETIC = "synthetic"        # generated by us, seeded


class WakeCategory(str, Enum):
    SUPER = "super"
    HEAVY = "heavy"
    B757 = "b757"
    LARGE = "large"
    SMALL = "small"


class SizeClass(str, Enum):
    REGIONAL = "regional"
    NARROWBODY = "narrowbody"
    WIDEBODY = "widebody"


SIZE_ORDER = {SizeClass.REGIONAL: 0, SizeClass.NARROWBODY: 1, SizeClass.WIDEBODY: 2}


# --------------------------------------------------------------------------- public

class FocalFlight(_Model):
    flight_id: str                       # e.g. "DL1846-2015-07-14"
    airline: str
    flight_number: int
    tail_number: str
    origin: str
    destination: str
    date: str                            # YYYY-MM-DD
    sched_departure_min: float           # destination-local
    sched_arrival_min: float             # in-block, destination-local
    taxi_out_min: float
    wake_category: WakeCategory
    size_class: SizeClass
    # Recorded DOT outcome: context only, never an input to decisions.
    recorded_arrival_delay_min: float | None = None
    recorded_weather_delay_min: float | None = None
    recorded_late_aircraft_delay_min: float | None = None


class RouteOption(_Model):
    route_id: str                        # "nominal" must exist; e.g. "reroute_west", "divert_CHA"
    air_time_min: float                  # pre-departure: wheels-off to landing; airborne: decision to landing
    trip_fuel_kg: float                  # fuel burned over air_time_min
    through_weather: bool = False        # crosses an active convective cell
    turbulence_min: float = 0.0          # expected minutes in moderate turbulence
    diversion_airport: str | None = None  # set => landing at an alternate, not the destination


class Gate(_Model):
    gate_id: str
    zone: str                            # taxiway zone used to reach the gate
    size: SizeClass                      # largest aircraft the gate accepts
    airline: str                         # owning airline or "COMMON"
    taxi_in_min: float                   # runway exit to in-block


class PublicInfo(_Model):
    decision_point: Literal["pre_departure", "airborne"]
    decision_time_min: float
    focal: FocalFlight
    routes: list[RouteOption]
    gates: list[Gate]                    # airport gate map (published, like an AIP chart)
    available_slots_min: list[float]     # free arrival slots published by ATC (GDP slot list)
    rbs_slot_min: float                  # slot given to the focal flight by Ration-by-Schedule
    ready_min: float | None = None       # earliest off-block (e.g. late inbound aircraft); None = on schedule
    weather_summary: str = ""            # free text for agents' context


# -------------------------------------------------------------------------- private

class SequencedArrival(_Model):
    flight_id: str
    slot_min: float
    wake_category: WakeCategory


class ATCPrivate(_Model):
    base_aar_per_hour: float
    reduced_aar_per_hour: float
    arrival_sequence: list[SequencedArrival]   # other arrivals, focal excluded
    closed_taxiway_zones: list[str] = Field(default_factory=list)
    max_holding_min: float                      # holding-stack limit for this sector


class Connection(_Model):
    flight_id: str
    departure_min: float
    pax: int
    min_connect_min: float


class PilotPrivate(_Model):
    fuel_on_board_kg: float              # pre-departure: at take-off; airborne: at decision time
    holding_burn_kg_per_min: float
    alternate_airport: str
    alternate_fuel_kg: float             # destination -> alternate
    final_reserve_min: float = 30.0      # at holding burn
    crew_duty_end_min: float
    connections: list[Connection] = Field(default_factory=list)


class GateBooking(_Model):
    gate_id: str
    flight_id: str
    start_min: float
    end_min: float


class NextLeg(_Model):
    flight_id: str
    sched_departure_min: float


class GroundPrivate(_Model):
    planned_gate_id: str
    gate_bookings: list[GateBooking]     # other flights' gate occupancy
    min_turnaround_min: float
    next_leg: NextLeg | None = None
    ramp_crew_size: int
    crew_shift_end_min: float
    max_overtime_min: float


# ------------------------------------------------------------------------- scenario

class Scenario(_Model):
    scenario_id: str
    track: Literal["A", "B", "C", "D", "E"] = "A"
    seed: int = 0
    public: PublicInfo
    atc: ATCPrivate | None = None
    pilot: PilotPrivate | None = None
    ground: GroundPrivate | None = None
    provenance: dict[str, Provenance] = Field(default_factory=dict)  # field path -> origin

    def view(self, role: Role) -> Scenario:
        """Public data plus `role`'s own private data only. Give agents this, never the full scenario."""
        return self.model_copy(update={r: (getattr(self, r) if r == role else None) for r in ROLES})


# --------------------------------------------------------------------------- option

class Option(_Model):
    option_id: str
    route_id: str
    slot_min: float | None               # None for a diversion
    absorption: Literal["none", "ground", "airborne"]  # where the delay to the slot is taken
    gate_id: str | None                  # None for a diversion


# --------------------------------------------------------------------------- results

class RuleResult(_Model):
    rule_id: str                         # e.g. "PILOT-FUEL"
    role: Role
    passed: bool
    value: float | None = None
    limit: float | None = None
    unit: str = ""
    source: str                          # regulation / document the rule encodes
    detail: str = ""


class Timeline(_Model):
    """Public consequences of an option (computable from public data only)."""
    departure_min: float | None          # wheels-off; None if already airborne
    landing_min: float
    landing_airport: str
    in_block_min: float                  # at destination; for a diversion, estimated recovery in-block
    ground_delay_min: float
    airborne_holding_min: float
    arrival_delay_min: float             # in_block - scheduled arrival
    is_diversion: bool


class ATCOutcome(_Model):
    leader_gap_min: float | None
    leader_required_min: float | None
    follower_gap_min: float | None
    follower_required_min: float | None
    arrivals_in_hour: int                # rolling 60 min up to and including our landing
    holding_min: float


class PilotOutcome(_Model):
    fuel_at_landing_kg: float
    required_landing_fuel_kg: float
    extra_fuel_kg: float                 # vs nominal route with no holding
    missed_connection_pax: int
    turbulence_min: float
    duty_margin_min: float               # crew_duty_end - in-block (negative = exceeded)


class GroundOutcome(_Model):
    gate_conflict_with: str | None
    gate_changed: bool
    overtime_min: float
    next_leg_delay_min: float


class Outcome(_Model):
    timeline: Timeline
    atc: ATCOutcome | None = None
    pilot: PilotOutcome | None = None
    ground: GroundOutcome | None = None


class CostBreakdown(_Model):
    role: Role
    components_usd: dict[str, float]
    total_usd: float


class EvaluatedOption(_Model):
    option: Option
    outcome: Outcome
    rule_results: list[RuleResult]
    costs: dict[str, CostBreakdown]      # keyed by role
    global_cost_usd: float
    feasible: bool                       # every hard rule passed


class PlanResult(_Model):
    method: str                          # "fcfs_rbs", "best_possible", ...
    status: Literal["plan", "escalate"]
    chosen: EvaluatedOption | None
    n_options: int
    n_feasible: int
    reason: str = ""
